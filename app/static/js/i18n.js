export function getLang() { return current; }

export function setLang(lang) {
  current = ORDER.includes(lang) ? lang : DEFAULT;
  document.documentElement.lang = current;
}

/** Pick the initial language: saved choice → Telegram language → browser language → Uzbek. */
export function detectLang(saved, telegramCode) {
  for (const candidate of [saved, telegramCode, navigator.language]) {
    const code = (candidate || '').slice(0, 2).toLowerCase();
    if (ORDER.includes(code)) return code;
  }
  return DEFAULT;
}

export function t(key, params) {
  const entry = D[key];
  let text = entry ? entry[ORDER.indexOf(current)] ?? entry[2] : key;
  if (params) text = text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
  return text;
}

export function subjectName(code) {
  const names = LANGUAGE_NAMES[code];
  return names ? names[ORDER.indexOf(current)] : code;
}
